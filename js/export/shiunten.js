  function addShiunSheet(wb, info, s) {
    var ws = portraitSheet(wb, sheetName(s.name));
    ws.pageSetup.fitToHeight = 0;
    var cols = [];
    var i;
    for (i = 0; i < 12; i++) { cols.push({ width: 8.25 }); }
    ws.columns = cols;
    var H = { size: 10, v: 'middle', h: 'center', fill: true };
    var C = { size: 10, v: 'middle' };
    var CC = { size: 10, v: 'middle', h: 'center' };
    var FILL = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFBFBFBF' } };
    var r = 1;
    textLine(ws, r, 12, s.title, 14, true, 28, 'left'); r++;
    textLine(ws, r, 12, '工事名　' + (info.kojiName || ''), 10, false, 20, 'left'); r++;
    if (s.lead) { textLine(ws, r, 12, s.lead, 10, false, 20, 'left'); r++; }
    ws.getRow(r).height = 8; r++;

    s.flow.forEach(function (row, n) {
      row.c.forEach(function (c) {
        var r2 = r + n + (c[4] ? c[4] - 1 : 0);
        if (c[3] === 'b' || c[3] === 'f') {
          box(ws, r + n, c[0], r2, c[1], c[2], CC);
          if (c[3] === 'f') { ws.getCell(r + n, c[0]).fill = FILL; }
        } else {
          if (c[0] !== c[1]) { ws.mergeCells(r + n, c[0], r + n, c[1]); }
          var cell = ws.getCell(r + n, c[0]);
          cell.value = c[2];
          cell.font = { name: FONT, size: 10 };
          cell.alignment = { horizontal: c[3] === 'n' ? 'left' : 'center', vertical: 'middle', wrapText: c[3] === 'n' };
        }
      });
      ws.getRow(r + n).height = row.h;
    });
    r += s.flow.length;
    ws.getRow(r).height = 8; r++;
    s.after.forEach(function (t) { textLine(ws, r, 12, t, 10, false, 20, 'left'); r++; });

    s.checks.forEach(function (ck, n) {
      if (n > 0) { ws.getRow(r - 1).addPageBreak(); }
      ws.getRow(r).height = 10; r++;
      textLine(ws, r, 12, ck.cap, 11, true, 22, 'left'); r++;
      box(ws, r, 1, r, 1, '項目', H);
      box(ws, r, 2, r, 5, ck.item, C);
      box(ws, r, 6, r, 7, '作業場所', H);
      box(ws, r, 8, r, 9, '', C);
      box(ws, r, 10, r, 10, '作業日', H);
      box(ws, r, 11, r, 12, '年　月　日', CC);
      ws.getRow(r).height = Math.max(24, lineCount(ck.item, 33, 10) * 14 + 8); r++;
      ws.getRow(r).height = 8; r++;
      box(ws, r, 1, r + 1, 1, '当該\n項目', H);
      box(ws, r, 2, r + 1, 5, '管理項目', H);
      box(ws, r, 6, r + 1, 7, '管理基準', H);
      box(ws, r, 8, r + 1, 9, '確認方法', H);
      box(ws, r, 10, r, 10, '担当者名', H);
      box(ws, r, 11, r, 12, '', C);
      box(ws, r + 1, 10, r + 1, 10, '確認日', H);
      box(ws, r + 1, 11, r + 1, 11, '合否', H);
      box(ws, r + 1, 12, r + 1, 12, '是正確認日', { size: 8, v: 'middle', h: 'center', fill: true, wrap: false });
      ws.getRow(r).height = 20;
      ws.getRow(r + 1).height = 20;
      r += 2;
      ck.rows.forEach(function (row) {
        box(ws, r, 1, r, 1, '□', { size: 12, v: 'middle', h: 'center' });
        box(ws, r, 2, r, 5, row[0], C);
        box(ws, r, 6, r, 7, row[1], CC);
        box(ws, r, 8, r, 9, row[2], CC);
        box(ws, r, 10, r, 10, '', C);
        box(ws, r, 11, r, 11, '', C);
        box(ws, r, 12, r, 12, '', C);
        var m = Math.max(lineCount(row[0], 33, 10), lineCount(row[1], 16.5, 10));
        ws.getRow(r).height = Math.max(26, m * 14 + 8);
        r++;
      });
      if (ck.note) { textLine(ws, r, 12, ck.note, 10, false, 22, 'left'); r++; }
    });
    return ws;
  }

